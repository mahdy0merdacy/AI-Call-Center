/** `typeof en` with literal strings widened, so other locales can differ. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => infer R
    ? (...args: A) => Widen<R>
    : T extends readonly (infer U)[]
      ? readonly Widen<U>[]
      : { readonly [K in keyof T]: Widen<T[K]> };

export type Messages = Widen<typeof en>;

const units = {
  en: { second: ['second', 'seconds'], minute: ['minute', 'minutes'], hour: ['hour', 'hours'] },
  fr: { second: ['seconde', 'secondes'], minute: ['minute', 'minutes'], hour: ['heure', 'heures'] },
} as const;

/** "42 seconds", "15 minutes", "1 hour" — rounded up so a countdown never undersells. */
export function formatDuration(totalSeconds: number, locale: keyof typeof units): string {
  const u = units[locale];
  const plural = (n: number, [one, many]: readonly [string, string]) =>
    `${n} ${n <= 1 ? one : many}`;
  const seconds = Math.max(0, Math.ceil(totalSeconds));
  if (seconds < 60) return plural(seconds, u.second);
  const minutes = Math.ceil(seconds / 60);
  if (minutes < 60) return plural(minutes, u.minute);
  return plural(Math.ceil(minutes / 60), u.hour);
}
