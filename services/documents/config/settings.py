# When set, tokens must carry exactly this issuer / audience. Set both in production.
JWT_ISSUER = os.environ.get('JWT_ISSUER', '')
JWT_AUDIENCE = os.environ.get('JWT_AUDIENCE', '')
# Only tokens whose role claim is in this comma-separated list may use the service
