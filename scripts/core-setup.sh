#!/usr/bin/env bash
# Prepare the core stack (deploy/compose.yaml). Idempotent: scripts/core-up.sh
# runs it on every start.
#
#   scripts/core-setup.sh                 # create what is missing, check prerequisites
#   scripts/core-setup.sh --skip-checks   # secrets and keys only
#   scripts/core-setup.sh --force         # NEW secrets and keys; the old ones are
#                                         # moved to deploy/.backup/<time>/
#
# Writes, and never prints:
#   deploy/.env    every password and secret key the stack needs (mode 600)
#   deploy/keys/   the portal's RS256 key pair, which signs and verifies JWTs
# Existing values are kept. A database volume keeps the password it was created
# with, so replacing one underneath it would lock the services out.
#
# DEPLOY_DIR=/some/dir writes there instead, e.g. to try this on a copy.

# "~/.cache/..." in the messages below is text for you to read, not a path.
# shellcheck disable=SC2088
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEPLOY_DIR=${DEPLOY_DIR:-$ROOT/deploy}
ENV_FILE=$DEPLOY_DIR/.env
KEY_DIR=$DEPLOY_DIR/keys

FORCE=0
CHECKS=1
for arg in "$@"; do
  case $arg in
    --force) FORCE=1 ;;
    --skip-checks) CHECKS=0 ;;
    -h | --help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"; exit 0 ;;
    *) echo "unknown option: $arg (see --help)" >&2; exit 2 ;;
  esac
done

if [ "$(id -u)" -eq 0 ]; then
  echo "Run this as your own user, not root: deploy/.env and the keys must be yours." >&2
  exit 1
fi
command -v openssl >/dev/null || { echo "openssl is required to generate secrets." >&2; exit 1; }

show() { printf '%s' "${1#"$ROOT"/}"; }   # a path, relative to the repo when inside it
umask 077                                 # everything created below is private
mkdir -p "$DEPLOY_DIR"

# ── --force: set the old secrets aside, never delete them ──────────────────────
if [ "$FORCE" = 1 ] && { [ -e "$ENV_FILE" ] || [ -e "$KEY_DIR" ]; }; then
  backup=$DEPLOY_DIR/.backup/$(date +%Y%m%d-%H%M%S)
  mkdir -p "$backup"
  if [ -e "$ENV_FILE" ]; then mv "$ENV_FILE" "$backup/.env"; fi
  if [ -e "$KEY_DIR" ]; then mv "$KEY_DIR" "$backup/keys"; fi
  echo "== --force: previous secrets and keys moved to $(show "$backup")"
  for volume in aicc-core_pgdata aicc-core_mongo-data; do
    if docker volume inspect "$volume" >/dev/null 2>&1; then
      echo "  WARNING: volume $volume still holds data created with the OLD passwords."
      echo "           Either restore them from the backup above, or wipe the data:"
      echo "           scripts/core-down.sh --volumes"
    fi
  done
fi

# ── JWT key pair ───────────────────────────────────────────────────────────────
echo "== JWT signing keys ($(show "$KEY_DIR"))"
mkdir -p "$KEY_DIR"
if [ -s "$KEY_DIR/jwt_private.pem" ]; then
  echo "  kept the existing RS256 key pair"
else
  # Its progress dots go to stderr; show them only if it fails.
  if ! err=$(openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 \
    -out "$KEY_DIR/jwt_private.pem" 2>&1); then
    printf '%s\n' "$err" >&2
    exit 1
  fi
  echo "  created an RS256 key pair (2048-bit)"
fi
# The public key is always re-derived, so it can never drift from the private one.
public=$(openssl pkey -in "$KEY_DIR/jwt_private.pem" -pubout)
if [ ! -f "$KEY_DIR/jwt_public.pem" ] || [ "$public" != "$(<"$KEY_DIR/jwt_public.pem")" ]; then
  printf '%s\n' "$public" >"$KEY_DIR/jwt_public.pem"
fi
# 640 plus the portal's group_add: its uid 10001 can read the private key, other
# users of this machine cannot (on k3s: a Secret volume with fsGroup).
chmod 750 "$KEY_DIR"
chmod 640 "$KEY_DIR/jwt_private.pem"
chmod 644 "$KEY_DIR/jwt_public.pem"

# ── deploy/.env ────────────────────────────────────────────────────────────────
echo "== secrets ($(show "$ENV_FILE"))"
if [ ! -s "$ENV_FILE" ]; then
  cat >"$ENV_FILE" <<'EOF'
# Generated by scripts/core-setup.sh for deploy/compose.yaml. Secrets: never commit
# or paste this file. Plain KEY=value lines without quotes, so docker compose,
# docker --env-file and kubectl create secret --from-env-file all read it alike.
# It is not a shell script: do not `source` it.
EOF
fi
chmod 600 "$ENV_FILE"

created=()
kept=()
# NAME VALUE: set NAME, replacing its line if there is one. The value goes from
# a variable straight into the file; nothing is echoed.
put() {
  local tmp
  tmp=$(mktemp "$DEPLOY_DIR/.env.XXXXXX")
  grep -v "^$1=" "$ENV_FILE" >"$tmp" || true
  printf '%s=%s\n' "$1" "$2" >>"$tmp"
  mv "$tmp" "$ENV_FILE"
}
# NAME COMMAND...: give NAME the command's output, unless it already has a value.
ensure() {
  local name=$1
  shift
  if grep -q "^$name=." "$ENV_FILE"; then
    kept+=("$name")
  else
    put "$name" "$("$@")"
    created+=("$name")
  fi
}
value() { printf '%s' "$1"; }
# Hex only for passwords: they are embedded in connection URLs.
hex() { openssl rand -hex "$1"; }

ensure AICC_UID value "$(id -u)"            # the TTS model cache and the key are yours
ensure AICC_GID value "$(id -g)"
ensure POSTGRES_DB value tenant_portal
ensure POSTGRES_USER value portal
ensure POSTGRES_PASSWORD hex 24
ensure VOICE_READER_PASSWORD hex 24
ensure MONGO_ROOT_USER value root
ensure MONGO_ROOT_PASSWORD hex 24
ensure MONGO_APP_USER value documents_app
ensure MONGO_APP_PASSWORD hex 24
ensure PORTAL_SECRET_KEY hex 32
ensure DOCUMENTS_SECRET_KEY hex 32
# The portal base64-decodes it and requires at least 32 bytes.
ensure MFA_ENCRYPTION_KEY openssl rand -base64 32
# Not a secret, and derived: always the current public key, on one line with
# literal \n, which is the form the documents service parses.
put JWT_PUBLIC_KEY "${public//$'\n'/\\n}"

[ ${#created[@]} -eq 0 ] || echo "  generated: ${created[*]}"
[ ${#kept[@]} -eq 0 ] || echo "  kept ${#kept[@]} existing values (not shown)"
echo "  JWT_PUBLIC_KEY matches $(show "$KEY_DIR")/jwt_public.pem"

[ "$CHECKS" = 1 ] || exit 0

# ── prerequisites ──────────────────────────────────────────────────────────────
missing=0
ok() { printf '  ok       %s\n' "$1"; }
warn() {
  printf '  warning  %s\n' "$1"
  shift
  [ $# -eq 0 ] || printf '           %s\n' "$@"
}
miss() {
  printf '  MISSING  %s\n' "$1"
  shift
  [ $# -eq 0 ] || printf '           %s\n' "$@"
  missing=$((missing + 1))
}

echo "== docker"
if ! command -v docker >/dev/null; then
  miss "docker" "https://docs.docker.com/engine/install/"
elif ! docker info >/dev/null 2>&1; then
  miss "a running docker daemon you can use" \
    "sudo systemctl start docker; and be in the docker group: sudo usermod -aG docker $USER"
else
  ok "docker $(docker version --format '{{.Server.Version}}' 2>/dev/null)"
  version=$(docker compose version --short 2>/dev/null || true)
  version=${version#v}
  major=${version%%.*}
  minor=${version#*.}
  minor=${minor%%.*}
  if [ -z "$version" ]; then
    miss "docker compose v2" "install the docker-compose-plugin package"
  elif [ "$major" -lt 2 ] || { [ "$major" -eq 2 ] && [ "$minor" -lt 24 ]; }; then
    miss "docker compose >= 2.24 (found $version)" "deploy/compose.yaml uses optional env_file entries"
  else
    ok "docker compose $version"
  fi
  # stt and tts use `gpus: all`: Docker needs the nvidia runtime or CDI devices.
  runtimes=$(docker info --format '{{range $name, $_ := .Runtimes}}{{$name}} {{end}}' 2>/dev/null || true)
  devices=$(docker info --format '{{json .DiscoveredDevices}}' 2>/dev/null || true)
  if [[ " $runtimes " == *" nvidia "* || "$devices" == *nvidia.com/gpu* ]]; then
    ok "NVIDIA container runtime"
  else
    miss "NVIDIA Container Toolkit (stt and tts run with gpus: all)" \
      "install nvidia-container-toolkit, then either" \
      "  sudo nvidia-ctk runtime configure --runtime=docker && sudo systemctl restart docker" \
      "or CDI: sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml"
  fi
fi
if command -v nvidia-smi >/dev/null && gpu=$(nvidia-smi --query-gpu=name,driver_version --format=csv,noheader 2>/dev/null); then
  ok "GPU: ${gpu%%$'\n'*}"
else
  miss "the NVIDIA driver (nvidia-smi); STT's CUDA 13 needs driver >= 580"
fi

echo "== models (mounted read-only from your caches; nothing downloads at runtime)"
cache=$HOME/.cache
if [ -s "$cache/whisper/small.pt" ]; then
  ok "~/.cache/whisper/small.pt (STT)"
else
  miss "~/.cache/whisper/small.pt (STT)" \
    "curl -L --create-dirs -o ~/.cache/whisper/small.pt https://openaipublic.azureedge.net/main/whisper/models/9ecf779972d90ba49c06d968637d720dd632c55bbf19d441fb42bf17a411e794/small.pt"
fi
for model in nvidia/magpie_tts_multilingual_357m nvidia/nemo-nano-codec-22khz-1.89kbps-21.5fps; do
  if [ -n "$(ls -A "$cache/nemo-speech/models/$model" 2>/dev/null)" ]; then
    ok "~/.cache/nemo-speech/models/$model (TTS)"
  else
    miss "~/.cache/nemo-speech/models/$model (TTS)" \
      "docker compose -f deploy/compose.yaml build tts && mkdir -p ~/.cache/nemo-speech/models" \
      "docker run --rm --gpus all --user \"\$(id -u):\$(id -g)\" -v ~/.cache/nemo-speech/models:/models/nemo-speech:z aicc/tts:dev pull $model"
  fi
done
bge=$cache/huggingface/hub/models--BAAI--bge-m3
snapshot=$(find "$bge/snapshots" -mindepth 1 -maxdepth 1 -type d 2>/dev/null | head -1)
if [ -n "$snapshot" ] && [ -s "$snapshot/modules.json" ] &&
  { [ -s "$snapshot/pytorch_model.bin" ] || [ -s "$snapshot/model.safetensors" ]; } &&
  [ -z "$(find "$bge/blobs" -name '*.incomplete' 2>/dev/null | head -1)" ]; then
  ok "~/.cache/huggingface: BAAI/bge-m3 (knowledge)"
else
  miss "BAAI/bge-m3 in ~/.cache/huggingface (knowledge runs with HF_HUB_OFFLINE=1)" \
    "HF_HUB_DISABLE_XET=1 .venv/bin/python -c \"from huggingface_hub import snapshot_download; snapshot_download('BAAI/bge-m3', allow_patterns=['*.json', 'pytorch_model.bin', 'sentencepiece.bpe.model'])\"" \
    "(a download in progress also shows here until it completes)"
fi

echo "== this machine"
if [ -f "$ROOT/.env" ] && grep -q '^GROQ_API_KEY=.' "$ROOT/.env"; then
  ok "GROQ_API_KEY in the root .env (not shown)"
else
  warn "no GROQ_API_KEY in the root .env: the stack starts, but the agent cannot reply" \
    "add a line GROQ_API_KEY=... to $(show "$ROOT/.env")"
fi
mem_gb=$(awk '/^MemTotal:/ { printf "%d", $2 / 1048576 }' /proc/meminfo 2>/dev/null || echo 0)
# An estimate, not a measurement: bge-m3 alone is ~2.3 GB of weights, and the
# memory limits in compose.yaml add up to ~17 GB.
if [ "$mem_gb" -ge 14 ]; then
  ok "${mem_gb} GB RAM (expect roughly 9 GB in use once warm)"
else
  warn "${mem_gb} GB RAM: expect roughly 9 GB in use once warm (knowledge alone ~3 GB)"
fi
# A port held by someone else makes `up` fail; ours are fine while the stack runs.
if command -v docker >/dev/null && [ -n "$(docker ps -q --filter label=com.docker.compose.project=aicc-core 2>/dev/null)" ]; then
  ok "ports 8080 8082 8025 5434 (the core stack holds them)"
elif command -v ss >/dev/null; then
  busy=0
  for port in 8080 8082 8025 5434; do
    if [ -n "$(ss -ltnH "sport = :$port" 2>/dev/null)" ]; then
      miss "port $port is in use by another program" "ss -ltnp 'sport = :$port' shows which"
      busy=1
    fi
  done
  [ "$busy" = 1 ] || ok "ports 8080 8082 8025 5434 are free"
fi

echo
if [ "$missing" -gt 0 ]; then
  echo "$missing prerequisite(s) missing (see above). Secrets and keys are ready." >&2
  exit 1
fi
echo "Ready: scripts/core-up.sh"
